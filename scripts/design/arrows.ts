// Each handmade level's optimal solution as marked arrow keys; used by directions.ts and the tests.
import { initialState, step } from '../../src/game/rules';
import { solve } from '../../src/game/solver';
import { Dir, Level } from '../../src/game/types';
import { HANDMADE } from '../../src/levels';

const ARROW: Record<Dir, string> = { up: '↑', down: '↓', left: '←', right: '→' };
// Seen from below, the ceiling is mirrored north to south, so there ↑ and ↓ swap.
const CEILING_ARROW: Record<Dir, string> = { ...ARROW, up: '↓', down: '↑' };

/** The solution as marked arrows in groups of five, one group per line. */
export function directions(level: Level): string[] {
  const moves = solve(level)?.moves;
  if (!moves) return ['(no solution)'];
  let state = initialState(level);
  const marked = moves.map((dir) => {
    const arrow = (state.layer ? CEILING_ARROW : ARROW)[dir];
    const r = step(level, state, dir);
    state = r.state;
    const kinds = new Set(r.motions.map((m) => m.kind));
    return (
      arrow +
      (kinds.has('fly') ? '✈' : '') +
      (r.toggled || r.pressed.length ? '●' : '') +
      (kinds.has('flip') ? '⇄' : '') +
      (r.outcome === 'win' ? '✔' : '')
    );
  });
  const lines: string[] = [];
  for (let i = 0; i < marked.length; i += 5) {
    const from = String(i + 1).padStart(2);
    const to = String(Math.min(i + 5, marked.length)).padStart(2);
    lines.push(`${from}-${to}  ${marked.slice(i, i + 5).join(' ')}`);
  }
  return lines;
}

export function solutionsMarkdown(): string {
  const out = [
    '# SkyTumble solutions',
    '',
    'Generated by `npm run -s directions -- --write`; `npm test` fails when it is out of date.',
    'Arrows are the keys at the starting view (↑ rolls toward the top of the board); turning the view',
    'with Q/E changes them. After a move: ✈ a flight, ● a switch press, ⇄ a flip, ✔ the win.',
    '',
  ];
  for (const h of HANDMADE) {
    out.push(`## \`${h.id}\` ${h.name}`.trimEnd(), '', '```', ...directions(h.level), '```', '');
  }
  return out.join('\n');
}
